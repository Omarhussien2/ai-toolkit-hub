const commonAgentLibraries = ["agent skills", "automation", "developer workflow"];

function repo(input) {
  const [owner, name] = input.full_name.split("/");
  return {
    legacy_id: `github:${input.full_name.toLowerCase()}`,
    name: input.name || name,
    name_en: input.name || name,
    description: input.description,
    url: `https://github.com/${input.full_name}`,
    github_owner: owner,
    github_repo: name,
    github_full_name: input.full_name,
    github_stars: input.stars,
    github_language: input.language || null,
    github_license: input.license || null,
    tags: Array.from(new Set(["github", ...(input.tags || [])])),
    use_cases: input.use_cases || [],
    libraries: input.libraries || [],
    notes: input.notes || null,
  };
}

